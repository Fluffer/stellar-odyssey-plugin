#!/usr/bin/env node
// Bundles the engine-cooldown alert into extension/content.js, the content
// script of the browser extension for the web version of the game
// (https://steam.stellarodyssey.app/). The extension needs no host process:
// the browser loads the script into the game page on every visit.
//
//   node build-extension.js [--lead 10] [--step 5] [--after 30] [--volume 0.5] [--poll 250] [--no-button]
//
// The values become the extension's defaults. They can be overridden without
// rebuilding from the game page's DevTools console:
//   localStorage.setItem("soEngineAlert.cfg", JSON.stringify({ leadMs: 15000, volume: 0.8 }))
// (reload the page afterwards).

const fs = require("fs");
const path = require("path");
const { normalizeConfig } = require("./lib/schedule");
const inj = require("./lib/injected");

const LS_CFG = "soEngineAlert.cfg";

function parseArgs(argv) {
  const o = { lead: 10, step: 5, after: 30, volume: 0.5, poll: 250, button: true, galaxy: true, pages: true, nodeMin: 90 };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const next = () => argv[++i];
    if (a === "--lead") o.lead = Number(next());
    else if (a === "--step") o.step = Number(next());
    else if (a === "--after") o.after = Number(next());
    else if (a === "--volume") o.volume = Number(next());
    else if (a === "--poll") o.poll = Number(next());
    else if (a === "--no-button") o.button = false;
    else if (a === "--no-galaxy") o.galaxy = false;
    else if (a === "--no-pages") o.pages = false;
    else if (a === "--node-min") o.nodeMin = Number(next());
    else { console.error("unknown option: " + a); process.exit(1); }
  }
  for (const k of ["lead", "step", "after", "volume", "poll", "nodeMin"]) {
    if (!Number.isFinite(o[k]) || o[k] < 0) { console.error("--" + k + " must be a non-negative number"); process.exit(1); }
  }
  if (o.step === 0) { console.error("--step must be > 0"); process.exit(1); }
  return o;
}

function buildContentScript(cfg) {
  return `// Generated by build-extension.js - do not edit; edit lib/page-core.js and rebuild.
// Stellar Odyssey engine-cooldown alert, v${inj.PLUGIN_VERSION}.
(function () {
  "use strict";
  var DEFAULTS = ${JSON.stringify(cfg)};
  var LS_CFG = ${JSON.stringify(LS_CFG)};
  var SCHED = (function () { var module = { exports: {} }; ${inj.SCHEDULE_SRC}\n; return module.exports; })();
  ${inj.sharedSources()}
  var cfg = Object.assign({}, DEFAULTS);
  try {
    var raw = localStorage.getItem(LS_CFG);
    if (raw) Object.assign(cfg, JSON.parse(raw));
  } catch (e) {}
  installEngineAlert(SCHED, cfg, ${JSON.stringify(inj.PLUGIN_VERSION)}, ${JSON.stringify(inj.LS_ENABLED)});
})();
`;
}

if (require.main === module) {
  const args = parseArgs(process.argv.slice(2));
  const cfg = Object.assign(normalizeConfig({
    leadMs: args.lead * 1000, stepMs: args.step * 1000, afterMs: args.after * 1000,
  }), { volume: Math.min(1, args.volume), pollMs: Math.max(50, args.poll), button: args.button, galaxy: args.galaxy, pages: args.pages, nodeMinQuality: args.nodeMin, console: true });
  const outDir = path.join(__dirname, "extension");
  fs.mkdirSync(outDir, { recursive: true });
  const out = path.join(outDir, "content.js");
  const src = buildContentScript(cfg);
  new Function(src); // syntax check before writing
  fs.writeFileSync(out, src);
  console.log("wrote " + out + " (" + src.length + " bytes); heads-up " + (cfg.leadMs / 1000) + "s before ready, then every " + (cfg.stepMs / 1000) + "s for " + (cfg.afterMs / 1000) + "s after ready, volume " + cfg.volume);
  console.log("load the 'extension' folder unpacked in Edge/Chrome: edge://extensions -> Developer mode -> Load unpacked");
}

module.exports = { buildContentScript, LS_CFG };
